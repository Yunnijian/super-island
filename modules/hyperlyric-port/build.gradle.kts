            "HyperLyric HookEntry runtime field changed"
        }
        val portRuntimeField = """    private var portHostModule: XposedModule? = null
"""
        val companionClose = """        )
    }

    private var _prefs: android.content.SharedPreferences? = null
"""
        check(withoutFocusWhitelist.contains(companionClose)) {
            "HyperLyric HookEntry companion boundary changed"
        }
        val portBinding = """        )

        private val portSystemUiHookedClassLoaders = java.util.Collections.synchronizedSet(
            java.util.Collections.newSetFromMap(java.util.WeakHashMap<ClassLoader, Boolean>())
        )

        /** Supplies the host adapter before the unmodified upstream load chain runs. */
        @JvmStatic
        fun preparePortRuntime(
            module: XposedModule,
            preferences: android.content.SharedPreferences,
            classLoader: ClassLoader
        ) {
            val runtime = instance ?: HookEntry().also { instance = it }
            runtime.portHostModule = module
            runtime._prefs = preferences
            HookLogger.module = module
            installPortSystemUiRuntime(module, classLoader)
        }

        /**
         * Runs the full SystemUI branch from HookEntry.onPackageLoaded with the existing
         * Super Island module as the only hook-handle owner.
         */
        @JvmStatic
        fun installPortSystemUiRuntime(module: XposedModule, classLoader: ClassLoader) {
            val runtime = instance ?: return
            if (!portSystemUiHookedClassLoaders.add(classLoader)) return

            StatusBarTextColorHooker.setTextColorChangedListener {
