        // that instance is SuperIslandXposedModule rather than HookEntry, while HookEntry.instance
        // remains the upstream owner of the bound RemotePreferences. Keep every effect algorithm
        // intact and adapt only that host-instance lookup.
        fun replacePortPreferenceOwner(
            relativePath: String,
            original: String,
            replacement: String,
        ) {
            val file = generatedRoot.resolve("com/lidesheng/hyperlyric/$relativePath")
            val source = file.readText()
            check(source.contains(original)) {
                "HyperLyric port preference owner changed: $relativePath"
            }
            file.writeText(source.replace(original, replacement))
        }
