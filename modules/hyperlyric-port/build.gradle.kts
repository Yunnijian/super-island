            .filter { it.isFile && it.extension == "kt" }
            .map { it.relativeTo(sourceRoot).invariantSeparatorsPath }
            .filterNot(::isHyperLyricPortExcludedSource)
            .toMutableSet()
            .apply {
                addAll(
                    hyperLyricOnlineSourceRoot.resolve("com/lidesheng/hyperlyric").walkTopDown()
                        .filter { it.isFile && it.extension == "kt" }
                        .map { it.relativeTo(hyperLyricOnlineSourceRoot.resolve("com/lidesheng/hyperlyric")).invariantSeparatorsPath },
                )
